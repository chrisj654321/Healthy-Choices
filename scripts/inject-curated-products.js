// ─── Merge and save ────────────────────────────────────────────────────────
function main() {
  const existing = JSON.parse(fs.readFileSync(OUTPUT_FILE, 'utf8'));
  const knownBarcodes = new Set(existing.products.map(p => p.barcode));

  const allRaw = [...chipsData, ...condimentsData];
  const toAdd = [];
  const skipped = [];

  for (const raw of allRaw) {
    if (knownBarcodes.has(raw.upc)) {
      skipped.push(raw.upc);
      continue;
    }
    knownBarcodes.add(raw.upc);
    toAdd.push(makeProduct(raw));
  }

  existing.products.push(...toAdd);
  existing.meta.lastRun = new Date().toISOString();
  existing.meta.totalCount = existing.products.length;
  existing.meta.lastBatchSize = toAdd.length;
  existing.meta.curatedCategories = existing.meta.curatedCategories || [];
  if (!existing.meta.curatedCategories.includes('chips_crackers_savory_snacks')) {
    existing.meta.curatedCategories.push('chips_crackers_savory_snacks');
  }
  if (!existing.meta.curatedCategories.includes('condiments_sauces_dressings')) {
    existing.meta.curatedCategories.push('condiments_sauces_dressings');
  }

  fs.writeFileSync(OUTPUT_FILE, JSON.stringify(existing, null, 2));

  console.log(`\nCurated product injection complete.`);
  console.log(`  Added:   ${toAdd.length} products`);
  console.log(`  Skipped: ${skipped.length} (barcode already in DB)`);
  console.log(`  Total in DB: ${existing.products.length}`);

  console.log('\nAdded products:');
  for (const p of toAdd) {
    const c = p.flags.totalConcerns;
    const tag = c >= 5 ? 'HIGH' : c >= 2 ? 'MED' : 'LOW';
    console.log(`  [${tag} ${c} concerns] ${p.name} (${p.brand}) — UPC ${p.barcode}`);
  }
  if (skipped.length > 0) {
    console.log(`\nSkipped UPCs (already present): ${skipped.join(', ')}`);
  }
}

main();
