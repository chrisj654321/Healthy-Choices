// ─── Detection lists (mirrors ingest-products.js) ─────────────────────────
const SEED_OILS = [
  'canola oil','soybean oil','sunflower oil','safflower oil',
  'corn oil','cottonseed oil','grapeseed oil','rice bran oil',
  'rapeseed oil','vegetable oil',
];
const ARTIFICIAL_DYES = [
  'red 40','red #40','yellow 5','yellow #5','yellow 6','yellow #6',
  'blue 1','blue #1','blue 2','blue #2','green 3','red 3',
  'caramel color iv','caramel color iii',
];
const SYNTHETIC_PRESERVATIVES = [
  'bha','bht','tbhq','sodium benzoate','potassium benzoate',
  'sodium nitrite','sodium nitrate','potassium sorbate',
  'propyl gallate','edta','calcium disodium edta',
  'sulfites','sulfur dioxide',
];
const ULTRA_PROCESSED_ADDITIVES = [
  'maltodextrin','modified corn starch','modified food starch',
  'monosodium glutamate','msg','autolyzed yeast','hydrolyzed',
  'soy protein isolate','natural flavors','natural flavor',
  'artificial flavors','artificial flavor','flavoring',
  'mono and diglycerides','monoglycerides','diglycerides',
  'carrageenan','xanthan gum','guar gum','cellulose gum',
  'polysorbate 80','polysorbate 60','corn syrup solids','dextrose',
  'enriched flour','bleached flour','soy lecithin','corn starch',
];
const HFCS_TERMS = ['high fructose corn syrup','high-fructose corn syrup','hfcs'];

function flagIngredients(ingredientsArray) {
  const text = (ingredientsArray || []).join(' | ').toLowerCase();
  const flags = {
    seedOils: [...new Set(SEED_OILS.filter(s => text.includes(s)))],
    ultraProcessedAdditives: [...new Set(ULTRA_PROCESSED_ADDITIVES.filter(a => text.includes(a)))],
    artificialDyes: [...new Set(ARTIFICIAL_DYES.filter(d => text.includes(d)))],
    highFructoseCornSyrup: HFCS_TERMS.some(t => text.includes(t)),
    syntheticPreservatives: [...new Set(SYNTHETIC_PRESERVATIVES.filter(p => text.includes(p)))],
  };
  flags.totalConcerns =
    flags.seedOils.length + flags.ultraProcessedAdditives.length +
    flags.artificialDyes.length + (flags.highFructoseCornSyrup ? 1 : 0) +
    flags.syntheticPreservatives.length;
  return flags;
}

function scoreFunctionalBenefits(ingredientsArray, name) {
  const text = [(ingredientsArray || []).join(' | '), name || ''].join(' | ').toLowerCase();
  const organic = ['organic','usda organic','certified organic'].some(t => text.includes(t));
  return { adaptogens: [], fermented: [], grassFed: false, regenerative: false, organic, score: organic ? 1 : 0 };
}

function makeProduct(raw) {
  const ingredients = raw.ingredients;
  return {
    barcode: raw.upc,
    name: raw.name,
    brand: raw.brand,
    category: raw.category,
    image: null,
    servingSize: raw.serving_size,
    calories: raw.calories,
    ingredients,
    nutrition: {
      fat: raw.fat_g,
      saturatedFat: raw.sat_fat_g,
      sodium: raw.sodium_mg,
      carbs: raw.carbs_g,
      sugars: raw.sugars_g,
      protein: raw.protein_g,
    },
    source: 'curated',
    isVegan: raw.is_vegan,
    isGlutenFree: raw.is_gluten_free,
    parentCompany: raw.parent_company,
    whyDemographicScansIt: raw.why_this_demographic_scans_it,
    controversyFlag: raw.controversy_flag,
    flags: flagIngredients(ingredients),
    functionalBenefits: scoreFunctionalBenefits(ingredients, raw.name),
    ingestedAt: new Date().toISOString(),
  };
}

